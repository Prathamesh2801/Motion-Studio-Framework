import React from 'react';
import { staticFile, useVideoConfig } from 'remotion';
import {
  TransitionSeries,
  resolveTransition,
  Soundtrack,
  crossfadeForGrid,
  Scene,
  SectionHeader,
  Badge,
  Outro,
  useResponsive,
  useFormat,
} from '@/framework';
import { musicalTimeline, musicalDuration, GRID, TRANSITION } from './timeline.js';

/**
 * Musical demo — the GRID-LOCKED verification project (Phase 3).
 *
 * Every cut lands on a bar line, and the soundtrack's splice points come from
 * `timeline.derived.musicCuts` — derived from the same scene starts that
 * position the picture, which is what guarantees sound and image cut together.
 *
 * The track is a generated test fixture (`scripts/make-test-track.mjs`): an
 * accented click on every downbeat plus a sustained pad, so both the grid
 * alignment and the one-bar equal-power crossfade at the splice are audible.
 */
const Beat = ({ eyebrow, title, background, badge }) => {
  const { responsive } = useResponsive();
  const { px } = useFormat();
  const align = responsive({ landscape: 'left', vertical: 'center' });

  return (
    <Scene background={background} camera="push">
      <div
        style={{
          display: 'flex',
          flexDirection: 'column',
          alignItems: align === 'center' ? 'center' : 'flex-start',
          gap: px(36),
          width: '100%',
          maxWidth: px(1300),
        }}
      >
        {badge ? <Badge delay={2}>{badge}</Badge> : null}
        <SectionHeader align={align} eyebrow={eyebrow} title={title} gradient rule delay={6} maxWidth={1150} />
      </div>
    </Scene>
  );
};

const SCENES = {
  open: () => <Beat badge="Bar 0" eyebrow="Bars timebase" title={'Cuts that land\non the grid.'} background="hearth" />,
  'beat-1': () => <Beat badge="Bar 2" eyebrow="Plays on" title="No splice here." background="studio" />,
  carousel: () => <Beat badge="Bar 8 · splice" eyebrow="Phrase boundary" title="The music jumps." background="workshop" />,
  close: () => (
    <Scene background="hearth" camera="pushIn">
      <Outro brandName="Grid-locked" tagline="Sound and picture cut on the same frame." website="motion-studio-framework" delay={4} />
    </Scene>
  ),
};

export const MusicalDemo = () => {
  const { fps } = useVideoConfig();
  const timeline = musicalTimeline(fps);
  const transition = resolveTransition({ type: 'fade', duration: TRANSITION });

  return (
    <>
      <TransitionSeries>
        {timeline.scenes.flatMap((scene, index) => {
          const SceneComponent = SCENES[scene.id];
          const nodes = [
            <TransitionSeries.Sequence key={scene.id} durationInFrames={scene.durationInFrames}>
              <SceneComponent />
            </TransitionSeries.Sequence>,
          ];
          if (index < timeline.scenes.length - 1) {
            nodes.push(
              <TransitionSeries.Transition
                key={`${scene.id}-transition`}
                presentation={transition.presentation}
                timing={transition.timing}
              />,
            );
          }
          return nodes;
        })}
      </TransitionSeries>

      {/*
        Raw `staticFile` here on purpose, against the usual rule in
        docs/AUTHORING.md. This WAV is a FRAMEWORK test fixture (generated by
        `npm run make:test-track`) shared by this demo and the showcase — it is
        not a project asset, so it lives at `public/assets/` rather than under
        `public/projects/<id>/`. A real project uses `assetsFor('<project>')`.
      */}
      <Soundtrack
        src={staticFile('assets/music/grid-120bpm.wav')}
        cuts={timeline.derived.musicCuts}
        crossfadeFrames={crossfadeForGrid(GRID, fps)}
      />
    </>
  );
};

export { musicalDuration };
export default MusicalDemo;
