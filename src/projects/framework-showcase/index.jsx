import React from 'react';
import { useVideoConfig, staticFile } from 'remotion';
import { StandardFilm } from '@/templates';
import { showcaseTimeline, showcaseDuration } from './timeline.js';
import { TitleChapter, OutroChapter } from './chapters/bookends.jsx';
import { MotionChapter, CameraChapter } from './chapters/motion.jsx';
import { TypographyChapter, ComponentsChapter } from './chapters/design.jsx';
import { LayoutsChapter, TemplatesChapter } from './chapters/structure.jsx';
import { TimelineChapter, AudioChapter, ThemeChapter } from './chapters/systems.jsx';

/**
 * FrameworkShowcase — the official engineering validation film.
 *
 * This is NOT a narrative piece. Its job is to fail loudly when a subsystem
 * regresses, and it is the composition to re-render after any framework change
 * or dependency upgrade.
 *
 * ── HOW IT IS STRUCTURED, AND WHY ───────────────────────────────────────────
 * One chapter per subsystem, each isolating a single system. That isolation is
 * the whole design: when a still looks wrong, the chapter slug in the corner
 * names the module to open. A denser film that mixed subsystems per section
 * would render faster and be worth much less, because a failure could no longer
 * be attributed.
 *
 * Chapters are ordered by dependency — motion, then camera, then layout, then
 * templates — so a break in an early chapter explains the breaks after it rather
 * than adding to the confusion.
 *
 * The film itself is assembled with `StandardFilm` over a `seconds` timeline,
 * i.e. through exactly the authoring surface a real project uses. If the
 * showcase needed a private code path to exist, that would be a finding.
 */

// The test fixture generated by `npm run make:test-track` — a 120 BPM bed. The
// showcase must render on a clean checkout, so a missing file is not fatal:
// `Soundtrack` returns null without a `src` and the film renders silent.
const MUSIC = staticFile('assets/music/grid-120bpm.wav');

export const FrameworkShowcase = () => {
  const { fps } = useVideoConfig();
  const timeline = showcaseTimeline(fps);

  // Splice the bed mid-film to exercise the equal-power crossfade. These cuts
  // are stated explicitly rather than read from `derived.musicCuts`, because
  // this film is on the `seconds` timebase and does not emit them — which is
  // itself the point: the audio engine takes cuts from whoever owns them.
  const musicCuts = [
    { from: 0, sourceSeconds: 0 },
    { from: timeline.byId.audio.from, sourceSeconds: 8 },
  ];

  return (
    <StandardFilm
      timeline={timeline}
      transition="fade"
      soundtrack={{ src: MUSIC, cuts: musicCuts, gain: 0.14 }}
      scenes={{
        title: <TitleChapter />,
        motion: <MotionChapter />,
        camera: <CameraChapter />,
        typography: <TypographyChapter />,
        components: <ComponentsChapter />,
        layouts: <LayoutsChapter />,
        templates: <TemplatesChapter />,
        timeline: <TimelineChapter />,
        audio: <AudioChapter musicSrc={MUSIC} />,
        theme: <ThemeChapter />,
        outro: <OutroChapter />,
      }}
    />
  );
};

export { showcaseDuration, showcaseTimeline };
export default FrameworkShowcase;
